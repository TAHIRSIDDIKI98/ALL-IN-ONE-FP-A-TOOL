#!/usr/bin/env node
/**
 * Deterministic SPEC.md -> /docs/user-guide/ Documentation Generator & Drift Gate
 * (MASTER_PROMPT §11.16 DOC2).
 *
 * - Reads SPEC.md, parses all `##` and `###` sections, scans for banned unverified claims,
 *   and renders deterministic markdown + JSON manifest artifacts under `docs/user-guide/`.
 * - Usage:
 *     node scripts/generate-docs.mjs --write [--root <dir>]
 *     node scripts/generate-docs.mjs --check [--root <dir>]
 */
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const BANNED_CLAIM_PATTERNS = [
  { re: /\bFeature\s+Complete\b/i, reason: 'banned "Feature Complete" claim' },
  { re: /\bProduction[- ]Ready\b/i, reason: 'banned "Production-Ready" claim' },
  { re: /v1\.0\.0-rc\d*/i, reason: 'premature release-candidate tag' },
  { re: /Coverage[_:\s]+100%/i, reason: 'unverified 100% coverage claim' },
  { re: /\bSOC\s*2\s+Type\s+II\s+Certified\b/i, reason: 'premature SOC 2 compliance claim' },
];

function sha256(content) {
  return createHash('sha256').update(content, 'utf8').digest('hex');
}

function slugify(title) {
  return title
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

export function parseSpecSections(specText) {
  const lines = specText.split(/\r?\n/);
  const h2 = [];
  const h3 = [];
  let current = null;

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    const h2Match = /^##\s+(.+?)\s*$/.exec(line);
    const h3Match = /^###\s+(.+?)\s*$/.exec(line);
    if (h2Match) {
      if (current) current.bodyLines.push();
      current = {
        level: 2,
        title: h2Match[1],
        slug: slugify(h2Match[1]),
        lineNo: i + 1,
        bodyLines: [],
      };
      h2.push(current);
    } else if (h3Match) {
      current = {
        level: 3,
        title: h3Match[1],
        slug: slugify(h3Match[1]),
        lineNo: i + 1,
        bodyLines: [],
      };
      h3.push(current);
    } else if (current) {
      current.bodyLines.push(line);
    }
  }

  return {
    h2: h2.map((s) => ({
      title: s.title,
      slug: s.slug,
      lineNo: s.lineNo,
      summary: extractFirstBulletOrParagraph(s.bodyLines),
      sha256: sha256(s.bodyLines.join('\n').trim()),
    })),
    h3: h3.map((s) => ({
      title: s.title,
      slug: s.slug,
      lineNo: s.lineNo,
      summary: extractFirstBulletOrParagraph(s.bodyLines),
      sha256: sha256(s.bodyLines.join('\n').trim()),
    })),
  };
}

function extractFirstBulletOrParagraph(bodyLines) {
  for (const raw of bodyLines) {
    const trimmed = raw.trim();
    if (trimmed.length === 0 || trimmed === '---' || trimmed.startsWith('```')) continue;
    return trimmed.replace(/^-\s+/, '');
  }
  return 'See SPEC.md for normative rules.';
}

export function buildUserGuideArtifacts(rootDir = process.cwd()) {
  const specPath = join(rootDir, 'SPEC.md');
  if (!existsSync(specPath)) {
    throw new Error(`Missing SPEC.md at ${specPath}`);
  }
  const specText = readFileSync(specPath, 'utf8');
  for (const { re, reason } of BANNED_CLAIM_PATTERNS) {
    const match = specText.match(re);
    if (match) {
      throw new Error(`SPEC.md contains ${reason}: "${match[0]}"`);
    }
  }

  const specSha = sha256(specText);
  const parsed = parseSpecSections(specText);

  const readmeLines = [
    '# OneFP&A User Guide (Generated from SPEC.md)',
    '',
    '<!-- AUTO-GENERATED by scripts/generate-docs.mjs — do not edit manually. -->',
    `Source specification SHA-256: \`${specSha}\``,
    '',
    '## Core Workflows & Seven-Screen Navigation',
    '',
    '1. **Sign In (`/sign-in`)**: Authenticate with Firebase or sandbox session credentials.',
    '2. **Company Setup (`/setup`)**: Configure company name, ISO-4217 base currency, and fiscal calendar (`12month`, `445`, `454`, `544`, `52_53`, `13x4`).',
    '3. **Chart of Accounts & Mapping (`/coa-mapper`)**: Import accounts, apply data-only industry packs (`saas`, `retail`, `manufacturing`), and publish effective-dated source mappings.',
    '4. **Import Wizard, Connectors & Migration (`/import`)**: Stage/commit actuals CSVs, budget CSVs, Google Sheets/QBO/Xero connectors, or dry-run/stage-commit onboarding cutover rehearsals.',
    '5. **Model Grid & Planning (`/model-grid`)**: Inspect Trial Balance drilldown, author driver plans, review rolling forecasts, manage approval workflows, and compile Workforce plans.',
    '6. **Financial Statements & Dashboards (`/statements`)**: Inspect P&L, Balance Sheet, Indirect Cash Flow (`A1–A5`), BvA, Flux/PVM bridges, and 18-KPI cited Dashboards.',
    '7. **Board Pack (`/board-pack`)**: Preview and download audit-tied XLSX, PDF, and PPTX board packs.',
    '',
    '## In-App Help, Timezones & Localization',
    '',
    '- Open **Help & Guide** in the top banner on any screen for context-keyed guidance (`data-help-key="help.screen.<route>"`).',
    '- Switch display locale (`en-US`, `ar-SA` RTL, `pseudo`) or display timezone (`UTC`, `America/New_York`, `Europe/London`, `Asia/Tokyo`); ledger accounting dates and decimal figures never change with display preferences.',
    '- Complete the 5-step **First-Company Onboarding Checklist** via `GET /api/companies/:companyId/onboarding/checklist` and record an audited sign-off (`POST …/onboarding/checklist/signoff`) once setup, CoA, actuals, and plan baseline steps are populated.',
    '',
    '## Specification Section Index (Top-Level)',
    '',
    ...parsed.h2.map((sec) => `- **${sec.title}** (SPEC.md line ${sec.lineNo}): ${sec.summary}`),
    '',
    'See [reference.md](./reference.md) for the complete generated contract reference and [manifest.json](./manifest.json) for deterministic section digests.',
    '',
  ];

  const referenceLines = [
    '# OneFP&A Specification Reference (Generated)',
    '',
    '<!-- AUTO-GENERATED by scripts/generate-docs.mjs — do not edit manually. -->',
    `Source \`SPEC.md\` SHA-256: \`${specSha}\``,
    '',
    '## Top-Level Sections',
    '',
    '| Section | SPEC Line | Digest (`sha256` prefix) | Summary |',
    '|---|---:|---|---|',
    ...parsed.h2.map(
      (s) => `| ${s.title.replace(/\|/g, '\\|')} | ${s.lineNo} | \`${s.sha256.slice(0, 12)}\` | ${s.summary.replace(/\|/g, '\\|')} |`,
    ),
    '',
    '## Module & Contract Subsections',
    '',
    '| Subsection | SPEC Line | Digest (`sha256` prefix) | Summary |',
    '|---|---:|---|---|',
    ...parsed.h3.map(
      (s) => `| ${s.title.replace(/\|/g, '\\|')} | ${s.lineNo} | \`${s.sha256.slice(0, 12)}\` | ${s.summary.replace(/\|/g, '\\|')} |`,
    ),
    '',
  ];

  const readmeContent = readmeLines.join('\n');
  const referenceContent = referenceLines.join('\n');
  const manifestObj = {
    generator: 'scripts/generate-docs.mjs',
    specSha256: specSha,
    topLevelCount: parsed.h2.length,
    subsectionCount: parsed.h3.length,
    sections: [...parsed.h2, ...parsed.h3].map((s) => ({
      title: s.title,
      slug: s.slug,
      lineNo: s.lineNo,
      sha256: s.sha256,
    })),
    artifacts: {
      'README.md': sha256(readmeContent),
      'reference.md': sha256(referenceContent),
    },
  };
  const manifestContent = `${JSON.stringify(manifestObj, null, 2)}\n`;

  return {
    files: {
      'docs/user-guide/README.md': readmeContent,
      'docs/user-guide/reference.md': referenceContent,
      'docs/user-guide/manifest.json': manifestContent,
    },
    specSha,
    sectionCount: parsed.h2.length + parsed.h3.length,
  };
}

export function checkOrWriteUserGuide(rootDir = process.cwd(), mode = 'check') {
  const { files, specSha, sectionCount } = buildUserGuideArtifacts(rootDir);
  const drifts = [];

  if (mode === 'write') {
    mkdirSync(join(rootDir, 'docs', 'user-guide'), { recursive: true });
    for (const [relPath, expected] of Object.entries(files)) {
      writeFileSync(join(rootDir, relPath), expected, 'utf8');
    }
    return { ok: true, drifts: [], specSha, sectionCount, written: Object.keys(files).length };
  }

  for (const [relPath, expected] of Object.entries(files)) {
    const absPath = join(rootDir, relPath);
    if (!existsSync(absPath)) {
      drifts.push(`${relPath}: missing generated file (run node scripts/generate-docs.mjs --write)`);
      continue;
    }
    const actual = readFileSync(absPath, 'utf8');
    if (actual !== expected) {
      drifts.push(`${relPath}: content drifted from SPEC.md (run node scripts/generate-docs.mjs --write)`);
    }
  }

  return { ok: drifts.length === 0, drifts, specSha, sectionCount, written: 0 };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const args = process.argv.slice(2);
  const rootIdx = args.indexOf('--root');
  const root = rootIdx !== -1 && args[rootIdx + 1] ? args[rootIdx + 1] : process.cwd();
  const mode = args.includes('--write') ? 'write' : 'check';

  const res = checkOrWriteUserGuide(root, mode);
  if (!res.ok) {
    console.error(`DOCS-SYNC GATE FAILED (${res.drifts.length} drift(s)):`);
    for (const d of res.drifts) console.error(`  ✗ ${d}`);
    process.exit(1);
  }
  if (mode === 'write') {
    console.log(
      `✓ generated ${res.written} user-guide file(s) from SPEC.md (${res.sectionCount} sections, sha256=${res.specSha.slice(0, 12)}).`,
    );
  } else {
    console.log(
      `✓ docs-sync green (${res.sectionCount} SPEC.md sections match /docs/user-guide/, sha256=${res.specSha.slice(0, 12)}).`,
    );
  }
}
